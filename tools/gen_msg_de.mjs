// The German texts of the robot's messages for the core, so a push from the
// device comes in the device's language (#10, step 5). The web app's table
// (web/src/lang/msg.ts) is the one source; this writes it as a C++ table,
// and tools/gen_msg_de.test.mjs fails when the two differ:
//   node tools/gen_msg_de.mjs > core/src/messages_de.inc
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// The object literal of msgDe, evaluated as JavaScript: the file is the repository's own
export function readTable(source) {
  const start = source.indexOf("{", source.indexOf("export const msgDe"));
  const end = source.lastIndexOf("};");
  if (start < 0 || end < start) throw new Error("msg.ts: no msgDe table");
  return Function(`"use strict"; return (${source.slice(start, end + 1)});`)();
}

const cpp = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

export function render(table) {
  const keys = Object.keys(table).sort();
  const lines = keys.map((k) => `    {"${cpp(k)}", "${cpp(table[k])}"},`);
  return `// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by tools/gen_msg_de.mjs from web/src/lang/msg.ts: the German
// templates of the robot's messages, by key. Do not edit.
// clang-format off
static const struct {
  const char* key;
  const char* text;
} kMessagesDe[] = {
${lines.join("\n")}
};
// clang-format on
`;
}

export const generate = () => render(readTable(readFileSync(join(root, "web/src/lang/msg.ts"), "utf8")));

if (import.meta.url === pathToFileURL(process.argv[1]).href) process.stdout.write(generate());
