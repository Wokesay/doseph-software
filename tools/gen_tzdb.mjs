// The time zone rules the core works with: for every zone of the IANA time
// zone database, the POSIX TZ rule from the footer of its compiled file
// (TZif version 2 or later), and the old names its links keep. The
// database is in the public domain. Run on a system with an up-to-date
// tzdata and commit the result:
//   node tools/gen_tzdb.mjs [/usr/share/zoneinfo] > core/src/tzdb.inc
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

// The rule a compiled zone file ends with, or null (no TZif, version 1, no footer)
export function footerRule(buf) {
  if (buf.length < 44 || buf.toString("latin1", 0, 4) !== "TZif" || buf[4] < 0x32) return null;
  const end = buf.length - 1;
  if (buf[end] !== 0x0a) return null;
  const start = buf.lastIndexOf(0x0a, end - 1);
  if (start < 0) return null;
  const rule = buf.toString("latin1", start + 1, end);
  return /^[\x21-\x7e]+$/.test(rule) ? rule : null;
}

// Zone name → rule, for every compiled zone below `root`; the copies under
// posix/ and right/ and the files without a zone name are left out
export function readZones(root) {
  const zones = new Map();
  const skip = new Set(["posix", "right", "posixrules", "localtime", "Factory"]);
  const walk = (dir, prefix) => {
    for (const name of readdirSync(dir).sort()) {
      if (!prefix && skip.has(name)) continue;
      const path = join(dir, name);
      const zone = prefix ? `${prefix}/${name}` : name;
      if (statSync(path).isDirectory()) walk(path, zone);
      else if (/^[A-Za-z]/.test(name)) {
        const rule = footerRule(readFileSync(path));
        if (rule) zones.set(zone, rule);
      }
    }
  };
  walk(root, "");
  return zones;
}

// The links of tzdata.zi ("L target alias"): old names such as Asia/Calcutta,
// which some browsers still report, take their target's rule
export function addLinks(zones, zi) {
  for (const m of zi.matchAll(/^L (\S+) (\S+)$/gm)) {
    const [, target, alias] = m;
    if (zones.has(target) && !zones.has(alias)) zones.set(alias, zones.get(target));
  }
  return zones;
}

export function render(zones, version) {
  const names = [...zones.keys()].sort();
  const lines = names.map((n) => `    {"${n}", "${zones.get(n)}"},`);
  return `// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by tools/gen_tzdb.mjs from the IANA time zone database${version ? `, version ${version}` : ""}
// (public domain): every zone with its POSIX TZ rule, sorted by name. Do not edit.
static constexpr struct {
  const char* zone;
  const char* rule;
} kZones[] = {
${lines.join("\n")}
};
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = process.argv[2] ?? "/usr/share/zoneinfo";
  let zi = "";
  try {
    zi = readFileSync(join(root, "tzdata.zi"), "latin1");
  } catch {}
  const version = zi.match(/^# version (\S+)/)?.[1] ?? "";
  const zones = addLinks(readZones(root), zi);
  if (zones.size < 300) {
    console.error(`gen_tzdb: only ${zones.size} zones under ${root}`);
    process.exit(1);
  }
  process.stdout.write(render(zones, version));
}
